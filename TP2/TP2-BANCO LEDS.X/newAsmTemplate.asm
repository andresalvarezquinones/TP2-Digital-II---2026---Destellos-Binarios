112 MOVLW D?3?
113 MOVWF REP
114 CRAW3:
115 CALL CRAWLING
116 BTFSC STATUS,C
117 GOTO SALIR_SECUENCIA
118 BANKSEL REP
119 DECFSZ REP,F
120 GOTO CRAW3
121 ; Repetir secuencias continuamente
122 GOTO MODO_SECUENCIA
