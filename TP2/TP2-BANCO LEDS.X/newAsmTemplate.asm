36 ; =========================================
37 ; MODO CONTADOR
38 ; =========================================
39 CONTADOR_MODO:
40 ; Mostrar contador
41 BANKSEL CONTADOR
42 MOVF CONTADOR,W
43 BANKSEL PORTD
44 MOVWF PORTD
45 ; Esperar que se presione RE0
46 ESPERAR_PRESION:
47 BANKSEL PORTE
48 BTFSC PORTE,0
49 GOTO ESPERAR_PRESION
50 ; Antirrebote
51 CALL DEMORA_50MS
52 BANKSEL PORTE
53 BTFSC PORTE,0
54 GOTO ESPERAR_PRESION
55 ; Empezar a medir cuanto dura la pulsacion
56 BANKSEL TIEMPO
57 CLRF TIEMPO
58 ; =========================================
59 ; MEDIR PULSACION
60 ; =========================================
61 MEDIR:
62 CALL DEMORA_50MS
63 BANKSEL TIEMPO
64 INCF TIEMPO,F
65 ; 20 x 50 ms = aproximadamente 1 segundo
66 MOVLW D?20?
67 SUBWF TIEMPO,W
68 BTFSC STATUS,Z
69 GOTO MODO_SECUENCIA
70 ; Ver si sigue apretado
71 BANKSEL PORTE
72 BTFSS PORTE,0
73 GOTO MEDIR
74 ; Si solto antes de 1 segundo fue toque corto
75 CALL DEMORA_50MS
76 BANKSEL CONTADOR
77 INCF CONTADOR,F
78 ; Si pasa de 255 vuelve a 1
79 GOTO CONTADOR_MODO
80 ; =========================================
81 ; MODO SECUENCIA
82 ; =========================================
83 MODO_SECUENCIA:
84 ; Esperar que suelte RE0
85 ESPERAR_SUELTA:
86 BANKSEL PORTE
87 BTFSS PORTE,0
88 GOTO ESPERAR_SUELTA
89 CALL DEMORA_50MS
90 ; Hacer RUNNING 3 veces
91 BANKSEL REP
92 MOVLW D?3?
93 MOVWF REP
94 RUN3:
95 CALL RUNNING
96 BTFSC STATUS,C
97 GOTO SALIR_SECUENCIA
98 BANKSEL REP
99 DECFSZ REP,F
100 GOTO RUN3
101 ; Hacer BRUNNING 3 veces
102 MOVLW D?3?
103 MOVWF REP
104 BRUN3:
105 CALL BRUNNING
106 BTFSC STATUS,C
107 GOTO SALIR_SECUENCIA
108 BANKSEL REP
109 DECFSZ REP,F
110 GOTO BRUN3
